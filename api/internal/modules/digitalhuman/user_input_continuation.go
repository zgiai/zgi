// digitalHumanUserInputContinuationRuntime is deliberately separate from the
// regular ChatRuntime interface. User questions are a continuation of an
// existing Agent Loop and must not be implemented as a new DigitalHuman run.
type digitalHumanUserInputContinuationRuntime interface {
	RunConfiguredUserInputContinuationStream(
		context.Context,
		runtimeservice.Scope,
		runtimeservice.Caller,
		runtimeservice.RunConfig,
		uuid.UUID,
		uuid.UUID,
		string,
		runtimedto.UserInputContinuationRequest,
		func(runtimeservice.StreamEvent) error,
	) (*runtimeservice.ChatResult, error)
}

type digitalHumanContinuationRunLookup interface {
	RunByMessageID(context.Context, uuid.UUID, uuid.UUID, uuid.UUID, uuid.UUID) (*Run, error)
}

// ContinueUserInput resumes a ChatRuntime user_input_request in the same
// conversation and Agent Loop. It is different from task/workflow approval:
// the request was generated by the model as a question and the answer must be
// fed back into the pending loop rather than treated as a new user turn.
func (s *RuntimeService) ContinueUserInput(
	ctx context.Context,
	scope Scope,
	digitalHumanID, conversationID, messageID uuid.UUID,
	requestID string,
	request runtimedto.UserInputContinuationRequest,
	onEvent func(runtimeservice.StreamEvent) error,
) (*runtimeservice.ChatResult, error) {
	if s == nil || digitalHumanID == uuid.Nil || conversationID == uuid.Nil || messageID == uuid.Nil ||
		strings.TrimSpace(requestID) == "" || onEvent == nil || len(request.Answers) == 0 {
		return nil, ErrInvalidRequest
	}

	continuationRuntime, ok := s.chat.(digitalHumanUserInputContinuationRuntime)
	if !ok {
		return nil, fmt.Errorf("digital human user input continuation is unavailable")
	}
	lookup, ok := s.store.(digitalHumanContinuationRunLookup)
	if !ok {
		return nil, fmt.Errorf("digital human continuation run lookup is unavailable")
	}
	run, err := lookup.RunByMessageID(ctx, scope.OrganizationID, scope.WorkspaceID, digitalHumanID, messageID)
	if err != nil {
		return nil, err
	}
	if !continuationRunOwnedByScope(run, scope, digitalHumanID) || run.ConversationID == nil || *run.ConversationID != conversationID || run.MessageID == nil || *run.MessageID != messageID {
		return nil, ErrConversationNotFound
	}

	resolved, event, err := decodeAndVerifyRun(run)
	if err != nil {
		return nil, err
	}
	config, cleanup, err := s.userInputContinuationConfig(ctx, run, resolved, event, scope)
	if err != nil {
		return nil, err
	}
	defer cleanup()

	_, runtimeScope, caller, err := s.conversationContext(scope, digitalHumanID)
	if err != nil {
		return nil, err
	}
	caller.RunID = cloneUUIDPointer(&run.ID)
	// The run waits with its question; answering resumes it, and the run
	// settles where the answer leaves the conversation. Without this the run
	// stayed waiting after the conversation moved on.
	held := run.Status == RunStatusWaiting && run.WaitingReason == runtimemodel.MessageStatusWaitingQuestion
	if held {
		if err := s.resumeHeldWorkflowRun(ctx, run); err != nil {
			return nil, err
		}
	}
	result, err := continuationRuntime.RunConfiguredUserInputContinuationStream(
		ctx, runtimeScope, caller, config, conversationID, messageID, strings.TrimSpace(requestID), request, onEvent,
	)
	if held {
		switch {
		case err != nil:
			// A rejected answer leaves the question open; hold the run again
			// unless the message moved on.
			if waiter, ok := s.store.(runWaitingStore); !ok ||
				waiter.MarkRunWaiting(context.WithoutCancel(ctx), run.ID, runtimemodel.MessageStatusWaitingQuestion, s.now()) != nil {
				s.settleWorkflowContinuationRun(ctx, run, "", "", nil)
			}
		case result != nil:
			s.settleWorkflowContinuationRun(ctx, run, result.Status, result.Answer, result.Metadata)
		}
	}
	return result, err
}

func continuationRunOwnedByScope(run *Run, scope Scope, digitalHumanID uuid.UUID) bool {
	if run == nil || run.DigitalHumanID != digitalHumanID || run.OrganizationID != scope.OrganizationID || run.WorkspaceID != scope.WorkspaceID {
		return false
	}
	if strings.TrimSpace(scope.Surface) != "" && strings.TrimSpace(run.Surface) != strings.TrimSpace(scope.Surface) {
		return false
	}
	if scope.UserSubjectID != nil && *scope.UserSubjectID != uuid.Nil {
		return run.UserSubjectID != nil && *run.UserSubjectID == *scope.UserSubjectID && run.UserSubjectKind == scope.UserSubjectKind
	}
	// Anonymous WebApp sessions intentionally cannot answer model questions.
	// Channel continuations are handled by the channel adapter and do not use
	// this HTTP surface.
	return false
}

// userInputContinuationConfig rebuilds the request-scoped capabilities from
// the immutable run snapshot. Closures and decrypted credentials are not
// persisted in the pending question metadata, so they must be restored before
// ChatRuntime resumes the original loop.
func (s *RuntimeService) userInputContinuationConfig(
	ctx context.Context,
	run *Run,
	resolved *ResolvedExecution,
	event invocation.Event,
	scope Scope,
) (runtimeservice.RunConfig, func(), error) {
	config, err := s.brain.RunConfig(resolved)
	if err != nil {
		return runtimeservice.RunConfig{}, func() {}, err
	}
	cleanup := func() {}
	s.attachAttachmentReader(&config, run, resolved, event, &scope)
	config.ConnectorRunID = run.ID.String()
	applyRunEndUserBilling(&config, run)
	if s.linux != nil {
		config.RuntimeToolFactory, err = s.prepareContinuationLinux(ctx, run, resolved, event, scope)
		if err != nil {
			return runtimeservice.RunConfig{}, cleanup, err
		}
	}

	if s.channelContext != nil && event.Origin.Kind == invocation.OriginChannel {
		preparation, prepareErr := s.channelContext.Prepare(ctx, run, resolved, event, config.ModelProvider, config.Model)
		if prepareErr != nil {
			return runtimeservice.RunConfig{}, cleanup, prepareErr
		}
		if preparation != nil {
			if addendum := strings.TrimSpace(preparation.SystemPromptAddendum); addendum != "" {
				config.SystemPrompt = strings.TrimSpace(config.SystemPrompt) + "\n\n" + addendum
			}
			config.RuntimeTools = append(config.RuntimeTools, preparation.Tools...)
		}
	}
	if s.memory != nil && !previewRun(run) {
		preparation, prepareErr := s.memory.Prepare(ctx, run, resolved, event)
		if prepareErr != nil {
			return runtimeservice.RunConfig{}, cleanup, prepareErr
		}
		if preparation != nil {
			if addendum := strings.TrimSpace(preparation.SystemPromptAddendum); addendum != "" {
				config.SystemPrompt = strings.TrimSpace(config.SystemPrompt) + "\n\n" + addendum
			}
			config.RuntimeTools = append(config.RuntimeTools, preparation.Tools...)
		}
	}
	if s.tasks != nil && !previewRun(run) {
		preparation, prepareErr := s.tasks.Prepare(ctx, run, event)
		if prepareErr != nil {
			return runtimeservice.RunConfig{}, cleanup, prepareErr
		}
		if preparation != nil {
			if addendum := strings.TrimSpace(preparation.SystemPromptAddendum); addendum != "" {
				config.SystemPrompt = strings.TrimSpace(config.SystemPrompt) + "\n\n" + addendum
			}
			config.RuntimeTools = append(config.RuntimeTools, preparation.Tools...)
		}
	}
	return config, cleanup, nil
}

type digitalHumanUserInputHandlerService interface {
	ContinueUserInput(context.Context, Scope, uuid.UUID, uuid.UUID, uuid.UUID, string, runtimedto.UserInputContinuationRequest, func(runtimeservice.StreamEvent) error) (*runtimeservice.ChatResult, error)
}

func (h *RuntimeHandler) ContinueUserInput(c *gin.Context) {
	scope, digitalHumanID, conversationID, messageID, ok := h.userInputIDs(c)
	if !ok {
		return
	}
	requestID := strings.TrimSpace(c.Param("request_id"))
	if requestID == "" {
		h.base.writeError(c, applicationError(ErrInvalidRequest, "digital_human.user_input.request"))
		return
	}
	var request runtimedto.UserInputContinuationRequest
	if !h.base.decode(c, &request) {
		return
	}
	request.Surface = SurfaceConsole
	h.continueUserInput(c, scope, digitalHumanID, conversationID, messageID, requestID, request)
}

func (h *RuntimeHandler) userInputIDs(c *gin.Context) (Scope, uuid.UUID, uuid.UUID, uuid.UUID, bool) {
	scope, digitalHumanID, ok := h.base.scopeAndID(c)
	if !ok {
		return Scope{}, uuid.Nil, uuid.Nil, uuid.Nil, false
	}
	scope.Surface = SurfaceConsole
	scope.PrincipalType = string(invocation.PrincipalAccount)
	scope.PrincipalID = scope.ActorID
	subjectID := scope.ActorID
	scope.UserSubjectKind = string(usersubject.Account)
	scope.UserSubjectID = &subjectID
	conversationID, err := uuid.Parse(strings.TrimSpace(c.Param("conversation_id")))
	if err != nil || conversationID == uuid.Nil {
		h.base.writeError(c, applicationError(ErrInvalidRequest, "digital_human.user_input.conversation"))
		return Scope{}, uuid.Nil, uuid.Nil, uuid.Nil, false
	}
	messageID, err := uuid.Parse(strings.TrimSpace(c.Param("message_id")))
	if err != nil || messageID == uuid.Nil {
		h.base.writeError(c, applicationError(ErrInvalidRequest, "digital_human.user_input.message"))
		return Scope{}, uuid.Nil, uuid.Nil, uuid.Nil, false
	}
	return scope, digitalHumanID, conversationID, messageID, true
}

// ContinueWebAppUserInput resumes a question for an authenticated landing
// page account. Anonymous webapp sessions deliberately have no user subject
// and cannot answer stateful model questions.
func (h *ExternalHandler) ContinueWebAppUserInput(c *gin.Context) {
	scope, access, conversationID, ok := h.webAppConversationRequest(c)
	if !ok {
		return
	}
	if scope.UserSubjectID == nil || *scope.UserSubjectID == uuid.Nil {
		h.writeAuthError(c, true)
		return
	}
	messageID, ok := parseUserInputMessageID(c, h.base, "digital_human.webapp.user_input.message")
	if !ok {
		return
	}
	requestID := strings.TrimSpace(c.Param("request_id"))
	if requestID == "" {
		h.writeApplicationError(c, ErrInvalidRequest, "digital_human.webapp.user_input.request")
		return
	}
	var request runtimedto.UserInputContinuationRequest
	if !h.base.decode(c, &request) {
		return
	}
	request.Surface = SurfaceWebApp
	writer := newDigitalHumanSSEWriter(c)
	writer.start(c.Request.Context())
	_, err := h.runtime.ContinueUserInput(c.Request.Context(), scope, access.Definition.ID, conversationID, messageID, requestID, request, func(event runtimeservice.StreamEvent) error {
		return writer.write(event.ID, event.EventType, redactConversationValue(event.Payload))
	})
	if err != nil && c.Request.Context().Err() == nil {
		_ = h.writeStreamError(writer, uuid.Nil, err)
	}
}

// ContinueAPIUserInput keeps the external API's user field as the stable
// subject selector. The API key remains only the authenticated principal.
func (h *ExternalHandler) ContinueAPIUserInput(c *gin.Context) {
	key, access, ok := h.apiAccess(c)
	if !ok {
		return
	}
	var raw struct {
		User             string                 `json:"user"`
		Answers          map[string]string      `json:"answers,omitempty"`
		Surface          string                 `json:"surface,omitempty"`
		RuntimeContext   string                 `json:"runtime_context,omitempty"`
		OperationContext map[string]interface{} `json:"operation_context,omitempty"`
	}
	if !h.base.decode(c, &raw) {
		return
	}
	scope, ok := h.apiUserScope(c, key, access, raw.User)
	if !ok {
		return
	}
	conversationID, ok := h.conversationID(c)
	if !ok {
		return
	}
	messageID, ok := parseUserInputMessageID(c, h.base, "digital_human.external.user_input.message")
	if !ok {
		return
	}
	requestID := strings.TrimSpace(c.Param("request_id"))
	if requestID == "" {
		h.writeApplicationError(c, ErrInvalidRequest, "digital_human.external.user_input.request")
		return
	}
	request := runtimedto.UserInputContinuationRequest{
		Answers: raw.Answers, Surface: SurfaceAPI, RuntimeContext: raw.RuntimeContext, OperationContext: raw.OperationContext,
	}
	writer := newDigitalHumanSSEWriter(c)
	writer.start(c.Request.Context())
	_, err := h.runtime.ContinueUserInput(c.Request.Context(), scope, access.Definition.ID, conversationID, messageID, requestID, request, func(event runtimeservice.StreamEvent) error {
		return writer.write(event.ID, event.EventType, redactConversationValue(event.Payload))
	})
	if err != nil && c.Request.Context().Err() == nil {
		_ = h.writeStreamError(writer, uuid.Nil, err)
	}
}

func parseUserInputMessageID(c *gin.Context, base *Handler, operation string) (uuid.UUID, bool) {
	messageID, err := uuid.Parse(strings.TrimSpace(c.Param("message_id")))
	if err != nil || messageID == uuid.Nil {
		base.writeError(c, applicationError(ErrInvalidRequest, operation))
		return uuid.Nil, false
	}
	return messageID, true
}

// continueUserInput writes the same event envelope used by Agent runtime
// continuations. The handler starts SSE before executing so all failures after
// validation become a safe stream error instead of a second HTTP response.
func (h *RuntimeHandler) continueUserInput(
	c *gin.Context,
	scope Scope,
	digitalHumanID, conversationID, messageID uuid.UUID,
	requestID string,
	request runtimedto.UserInputContinuationRequest,
) {
	service, ok := h.service.(digitalHumanUserInputHandlerService)
	if !ok {
		h.base.writeError(c, applicationError(ErrRunConflict, "digital_human.user_input.continue"))
		return
	}
	writer := newDigitalHumanSSEWriter(c)
	writer.start(c.Request.Context())
	_, err := service.ContinueUserInput(c.Request.Context(), scope, digitalHumanID, conversationID, messageID, requestID, request, func(event runtimeservice.StreamEvent) error {
		return writer.write(event.ID, event.EventType, redactConversationValue(event.Payload))
	})
	if err == nil || errors.Is(err, runtimeservice.ErrMessageStopped) || runtimeservice.IsFinalizedStreamError(err) {
		return
	}
	_ = writer.write("", "error", gin.H{"error": "digital human user input continuation failed"})
}
