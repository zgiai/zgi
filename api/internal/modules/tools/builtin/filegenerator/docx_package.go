// writeDocxPackage assembles a WordprocessingML package around the given
// w:body children.
func writeDocxPackage(body string) ([]byte, error) {
	parts := []struct {
		name    string
		content string
	}{
		{name: "[Content_Types].xml", content: docxContentTypesXML},
		{name: "_rels/.rels", content: docxPackageRelsXML},
		{name: "docProps/app.xml", content: docxAppPropsXML},
		{name: "docProps/core.xml", content: docxCorePropsXML},
		{name: "word/_rels/document.xml.rels", content: docxDocumentRelsXML},
		{name: "word/document.xml", content: docxDocumentHeader + body + docxDocumentFooter},
		{name: "word/styles.xml", content: docxStylesXML},
		{name: "word/settings.xml", content: docxSettingsXML},
		{name: "word/fontTable.xml", content: docxFontTableXML},
		{name: "word/theme/theme1.xml", content: docxThemeXML},
	}

	var buf bytes.Buffer
	writer := zip.NewWriter(&buf)
	for _, part := range parts {
		entry, err := writer.CreateHeader(&zip.FileHeader{Name: part.name, Method: zip.Deflate})
		if err != nil {
			_ = writer.Close()
			return nil, fmt.Errorf("failed to create DOCX entry %s: %w", part.name, err)
		}
		if _, err := entry.Write([]byte(part.content)); err != nil {
			_ = writer.Close()
			return nil, fmt.Errorf("failed to write DOCX entry %s: %w", part.name, err)
		}
	}
	if err := writer.Close(); err != nil {
		return nil, fmt.Errorf("failed to render DOCX: %w", err)
	}
	return buf.Bytes(), nil
}

// escapeDocxXML escapes text for use in XML character data or attribute
// values; characters that XML 1.0 forbids are replaced with U+FFFD.
func escapeDocxXML(value string) string {
	var out strings.Builder
	_ = xml.EscapeText(&out, []byte(value))
	return out.String()
}
